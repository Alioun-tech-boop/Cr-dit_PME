/* Vérification réelle du décodage, du mouvement et des commandes de l'accueil. */
const { chromium } = require('playwright-core');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const base = process.env.CREDIT_PREVIEW_URL || process.env.CREDIT_E2E_URL || 'http://127.0.0.1:8010';
const output = path.resolve('../output/home-videos');
fs.mkdirSync(output, { recursive: true });
let checks = 0;
function check(condition, text) { assert(condition, text); checks++; console.log('OK ' + text); }
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
  const errors = [];
  try {
    const context = await browser.newContext({ viewport: { width: 1365, height: 1000 }, reducedMotion: 'no-preference' });
    const page = await context.newPage();
    page.on('pageerror', e => errors.push(e.message));
    const externalMedia = [];
    page.on('request', r => { if (r.resourceType() === 'media' && !r.url().startsWith(base + '/')) externalMedia.push(r.url()); });
    await page.goto(base + '/#overview');
    await page.waitForFunction(() => document.querySelectorAll('.story video').length === 2 && [...document.querySelectorAll('.story video')].every(v => v.readyState >= 2 && !v.paused));
    check(true, 'Deux séquences réelles décodées et en lecture automatique');
    check(await page.locator('.story > img').count() === 0, 'Les anciennes photos de l’accueil sont remplacées');
    const metadata = await page.locator('.story video').evaluateAll(videos => videos.map(v => ({ duration: v.duration, muted: v.muted, loop: v.loop, inline: v.playsInline, width: v.videoWidth, height: v.videoHeight, time: v.currentTime })));
    check(metadata.every(v => v.duration === 8 && v.muted && v.loop && v.inline && v.width > 0), 'Clips de 8 secondes, silencieux, en boucle et inline');
    const first = page.locator('.story video').first();
    const before = await first.evaluate(v => v.currentTime);
    await page.waitForTimeout(500);
    check(await first.evaluate(v => v.currentTime) !== before, 'Les images vidéo avancent réellement');
    const pause = page.locator('.home-video-toggle').first();
    await pause.click();
    check(await first.evaluate(v => v.paused), 'Bouton pause opérationnel');
    await pause.focus();
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => !document.querySelector('.story video').paused);
    check(true, 'Reprise au clavier opérationnelle');
    await page.screenshot({ path: output + '/desktop.png', fullPage: true });
    await page.goto(base + '/#settings');
    await page.selectOption('[name=motion]', 'reduced');
    await page.click('#settings-form button[type=submit]');
    await page.goto(base + '/#overview');
    await page.waitForSelector('.home-video');
    await page.waitForTimeout(400);
    check(await page.locator('.story video').evaluateAll(v => v.every(x => x.paused && !x.getAttribute('src'))), 'Préférence de mouvement réduit : affiches sans téléchargement vidéo');
    await page.locator('.home-video-toggle').first().click();
    await page.waitForFunction(() => !document.querySelector('.story video').paused);
    check(true, 'Lecture explicite possible malgré le mouvement réduit');
    await page.goto(base + '/#requests');
    check(await page.locator('.story video').count() === 0, 'Navigation conservée et vidéos retirées en quittant l’accueil');
    check(externalMedia.length === 0, 'Aucun lecteur ou média tiers chargé');
    const mobileContext = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, reducedMotion: 'no-preference' });
    const mobile = await mobileContext.newPage();
    await mobile.goto(base + '/#overview');
    await mobile.locator('.stories').scrollIntoViewIfNeeded();
    await mobile.waitForFunction(() => !document.querySelector('.story video').paused);
    check(await mobile.locator('.story video').first().evaluate(v => v.playsInline), 'Lecture vidéo inline sur mobile');
    await mobile.screenshot({ path: output + '/mobile.png', fullPage: true });
    const reducedContext = await browser.newContext({ reducedMotion: 'reduce' });
    const reduced = await reducedContext.newPage();
    await reduced.goto(base + '/#overview');
    await reduced.waitForSelector('.home-video');
    check(await reduced.locator('.story video').evaluateAll(v => v.every(x => x.paused && !x.getAttribute('src'))), 'Préférence système de réduction des animations respectée');
    const savingContext = await browser.newContext();
    await savingContext.addInitScript(() => Object.defineProperty(navigator, 'connection', { value: { saveData: true, addEventListener() {} } }));
    const saving = await savingContext.newPage();
    await saving.goto(base + '/#overview');
    await saving.waitForSelector('.home-video');
    check(await saving.locator('.story video').evaluateAll(v => v.every(x => !x.getAttribute('src'))), 'Économie de données : pas de chargement automatique');
    const brokenContext = await browser.newContext();
    await brokenContext.route('**/assets/videos/*.mp4', r => r.abort());
    const broken = await brokenContext.newPage();
    await broken.goto(base + '/#overview');
    await broken.waitForFunction(() => [...document.querySelectorAll('.home-video-toggle')].some(b => b.disabled));
    check(await broken.locator('.story video').first().evaluate(v => Boolean(v.poster)), 'Échec réseau : affiche et indication explicite conservées');
    check(errors.length === 0, 'Aucune erreur JavaScript');
    fs.writeFileSync(output + '/checks.json', JSON.stringify({ checks, metadata, errors }, null, 2));
    console.log(checks + ' contrôles vidéo Chromium réussis.');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
