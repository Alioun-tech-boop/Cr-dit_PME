const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const dataSource=fs.readFileSync('dist/demo-data.js','utf8');
const context={window:{}};
vm.runInNewContext(dataSource,context);
const data=context.window.CREDIT_DEMO_DATA;
assert.ok(data && data.cases);
assert.deepEqual(Object.keys(data.cases).sort(),['business','individual']);
const person=data.cases.individual,company=data.cases.business;
assert.equal(person.core,'individuals');
assert.equal(person.periods.length,6);
assert.equal(person.periods[0].margin,'70000.00');
assert.equal(person.stress[0].after,'-30000.00');
assert.equal(person.variants.length,2);
assert.equal(company.core,'businesses');
assert.equal(company.periods.length,3);
assert.equal(company.periods[0].margin,'-163000.00');
assert.equal(company.deficits.length,1);
assert.equal(company.variants.every(v=>!v.compatible),true);
for(const item of [person,company]){
 assert.equal(item.scoring.criteria_score,null);
 assert.equal(item.scoring.model_status,'disabled_by_design');
 assert.equal(item.scoring.policy_status,'illustrative_not_validated');
 assert.equal(item.documentary_quality.authenticity_status,'not_assessed');
 assert.ok(item.source_case && item.source_report);
}
const ui=fs.readFileSync('dist/demo.js','utf8');
const router=fs.readFileSync('dist/journey.js','utf8');
const html=fs.readFileSync('dist/platform.html','utf8');
assert.match(ui,/function documents/);
assert.match(ui,/function analysis/);
assert.match(ui,/function simulations/);
assert.match(ui,/function restitution/);
assert.match(router,/CreditDemo\?\.render\(hash\)/);
assert.match(router,/CreditDemo\?\.decorateOverview\(\)/);
assert.ok(html.indexOf('demo-data.js')<html.indexOf('demo.js'));
assert.match(html,/demo\.css/);
assert.doesNotMatch(ui,/\bfetch\s*\(/);
assert.doesNotMatch(ui,/CreditServices/);
console.log('Démo guidée : deux parcours, rapports v2, garde-fous et intégration vérifiés.');
